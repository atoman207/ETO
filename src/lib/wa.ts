export function currentSekki(date = new Date()) {
  const md = (date.getMonth() + 1) * 100 + date.getDate();
  let found = SEKKI[SEKKI.length - 1];
  for (const s of SEKKI) {
    if (s[0] * 100 + s[1] <= md) found = s;
  }
  return { name: found[2], kana: found[3], meaning: found[4] };
}

export function wafuMonth(date = new Date()) {
  return WAFU_MONTHS[date.getMonth()];
}
